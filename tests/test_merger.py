"""
Tests for SmartMerger and AST preservation.
"""

from __future__ import annotations

from heurix.core.merger import SmartMerger


def test_smart_merger_preserves_custom_job():
    existing_yaml = """# Existing CI
name: CI
on: [push]
jobs:
  test:
    runs-on: ubuntu-22.04
    steps:
      - uses: actions/checkout@v3
  deploy_prod:
    runs-on: ubuntu-latest
    steps:
      - name: Deploy to Cloud
        run: echo deploy
"""

    new_yaml = """# Generated by Heurix
name: CI
on:
  push:
    branches: [main]
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Run pytest
        run: pytest
"""

    merger = SmartMerger()
    merged = merger.merge_yaml(existing_yaml, new_yaml)

    # Must preserve deploy_prod custom job
    assert "deploy_prod:" in merged
    assert "Deploy to Cloud" in merged
    # Must update test job
    assert "ubuntu-latest" in merged
    assert "pytest" in merged


def test_smart_merger_preserve_directive():
    existing_yaml = """name: CI
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      # @heurix:preserve
      - name: Slack Notification
        run: curl -X POST https://slack.com
"""

    new_yaml = """name: CI
jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: Run test
        run: npm test
"""

    merger = SmartMerger()
    merged = merger.merge_yaml(existing_yaml, new_yaml)

    assert "Slack Notification" in merged
    assert "npm test" in merged
